/**
 * Reads the data declarations from seedBudgetCatalog.js and emits a pure-SQL
 * seed file at server/schema/migrations/20260520_seed_budget_catalog.sql.
 *
 * Run once locally:
 *   node server/scripts/generateBudgetCatalogSql.js
 *
 * Then apply on prod with:
 *   mysql -u <user> -p <db> < server/schema/migrations/20260520_seed_budget_catalog.sql
 *
 * The output uses INSERT IGNORE-style conditional inserts so it's safe to re-run.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Read seedBudgetCatalog.js as text and extract the four constants.
const seedSource = fs.readFileSync(
    path.join(__dirname, 'seedBudgetCatalog.js'),
    'utf8',
);

function extractConst(name) {
    // Capture everything from `const NAME = ` up to the matching closing `];` or `};` at column 0
    const re = new RegExp(`const ${name} = ([\\s\\S]*?\\n[\\]}]);`, 'm');
    const m = seedSource.match(re);
    if (!m) throw new Error(`Could not find const ${name}`);
    // eslint-disable-next-line no-eval
    return eval(`(${m[1]})`);
}

const BUDGET_HEAD_GROUPS = extractConst('BUDGET_HEAD_GROUPS');
const SUB_HEAD_BY_HEAD = extractConst('SUB_HEAD_BY_HEAD');
const HOAC_SUBHEADS = extractConst('HOAC_SUBHEADS');
const EVENT_SUBHEAD_GROUPS = extractConst('EVENT_SUBHEAD_GROUPS');

const esc = (s) => String(s).replace(/'/g, "''");

const out = [];
out.push('-- ============================================');
out.push('-- Seed: budget_heads + budget_sub_heads');
out.push('-- Generated by server/scripts/generateBudgetCatalogSql.js');
out.push('-- Safe to re-run: every insert is conditional on the row not existing.');
out.push('-- Apply AFTER 20260520_create_budget_catalog.sql.');
out.push('-- ============================================');
out.push('');
out.push('START TRANSACTION;');
out.push('');

// ----- Heads -----
out.push('-- ----- HEADS -----');
let headOrder = 0;
const seenHeads = new Set();
for (const group of BUDGET_HEAD_GROUPS) {
    for (const headName of group.heads) {
        if (seenHeads.has(headName)) continue;
        seenHeads.add(headName);
        out.push(
            `INSERT INTO budget_heads (name, group_label, sort_order) ` +
            `SELECT '${esc(headName)}', '${esc(group.label)}', ${headOrder} ` +
            `FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM budget_heads WHERE name = '${esc(headName)}');`,
        );
        headOrder++;
    }
}
out.push('');

// ----- Head-specific sub-heads -----
out.push('-- ----- HEAD-SPECIFIC SUB-HEADS -----');
for (const [headName, subs] of Object.entries(SUB_HEAD_BY_HEAD)) {
    const seen = new Set();
    let order = 0;
    for (const sub of subs) {
        const key = sub.trim();
        if (!key || seen.has(key)) continue;
        seen.add(key);
        out.push(
            `INSERT INTO budget_sub_heads (name, head_id, scope, sort_order) ` +
            `SELECT '${esc(key)}', h.id, 'head-specific', ${order} ` +
            `FROM budget_heads h WHERE h.name = '${esc(headName)}' ` +
            `AND NOT EXISTS (SELECT 1 FROM budget_sub_heads s WHERE s.name = '${esc(key)}' AND s.head_id = h.id AND s.scope = 'head-specific');`,
        );
        order++;
    }
}
out.push('');

// ----- HOAC shared sub-heads -----
out.push('-- ----- HOAC SHARED SUB-HEADS -----');
for (const [eventType, subs] of Object.entries(HOAC_SUBHEADS)) {
    let order = 0;
    for (const sub of subs) {
        out.push(
            `INSERT INTO budget_sub_heads (name, scope, event_type, sort_order) ` +
            `SELECT '${esc(sub)}', 'hoac-shared', '${esc(eventType)}', ${order} ` +
            `FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM budget_sub_heads WHERE name = '${esc(sub)}' AND scope = 'hoac-shared' AND event_type = '${esc(eventType)}');`,
        );
        order++;
    }
}
out.push('');

// ----- Event-specific sub-heads -----
out.push('-- ----- EVENT-SPECIFIC SUB-HEADS -----');
for (const [eventType, groups] of Object.entries(EVENT_SUBHEAD_GROUPS)) {
    let order = 0;
    for (const { group, items } of groups) {
        for (const item of items) {
            out.push(
                `INSERT INTO budget_sub_heads (name, scope, event_type, group_label, sort_order) ` +
                `SELECT '${esc(item)}', 'event-specific', '${esc(eventType)}', '${esc(group)}', ${order} ` +
                `FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM budget_sub_heads WHERE name = '${esc(item)}' AND scope = 'event-specific' AND event_type = '${esc(eventType)}' AND group_label = '${esc(group)}');`,
            );
            order++;
        }
    }
}
out.push('');
out.push('COMMIT;');
out.push('');

const outputPath = path.join(
    __dirname,
    '..',
    'schema',
    'migrations',
    '20260520_seed_budget_catalog.sql',
);
fs.writeFileSync(outputPath, out.join('\n'), 'utf8');
console.log(`Wrote ${outputPath}`);
console.log(`Lines: ${out.length}`);
